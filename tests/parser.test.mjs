import test from 'node:test';
import assert from 'node:assert/strict';
import {parseDNA, normalizeGenotype, normalizeChromosome, isCalledDiploidSnp, isNoCall} from '../dist/dna-parser.js';

test('23andMe TSV: header, build, no-call and dosage are parsed without upload',()=>{
  const raw='# generated by 23andMe\n# genome build 37\n# rsid\tchromosome\tposition\tgenotype\nrs1800562\t6\t26093141\tAG\nrs4988235\t2\t136608646\t--';
  const data=parseDNA(raw);
  assert.equal(data.format,'23andMe / TSV');
  assert.equal(data.build,'37');
  assert.equal(data.records.get('rs1800562').genotype,'AG');
  assert.equal(data.records.get('rs4988235').genotype,'--');
  assert.equal(data.records.size,2);
});
test('MyHeritage CSV: BOM, comments, uppercase header and quoted values',()=>{
  const raw='\ufeff## MyHeritage DNA raw data\n# Genome build 38\nRSID,CHROMOSOME,POSITION,RESULT\n"rs762551","15","74749576","CA"\n"rs1800562","6","26093141","GG"';
  const data=parseDNA(raw);
  assert.equal(data.format,'MyHeritage CSV');
  assert.equal(data.build,'38');
  assert.equal(data.records.get('rs762551').genotype,'AC'); // unordered pair
  assert.equal(data.records.get('rs1800562').genotype,'GG');
});
test('MyHeritage five columns: allele1/allele2, CRLF, lower case',()=>{
  const raw='rsid\tchromosome\tposition\tallele1\tallele2\r\nrs762551\t15\t74749576\tc\ta\r\n';
  assert.equal(parseDNA(raw).records.get('rs762551').genotype,'AC');
});
test('headerless genotype rows are accepted and skip junk',()=>{
  const data=parseDNA('rs1\t1\t101\tAA\nrsBAD\t1\t102\tCC\nrs2\tchrX\t234\tTG\nrs3\tMT\t332\tII\n');
  assert.equal(data.records.size,3);
  assert.equal(data.records.get('rs2').genotype,'GT');
  assert.equal(data.records.get('rs2').chr,'X');
  assert.equal(data.skipped,1);
});
test('duplicates with the same call do not produce extra markers',()=>{
  const data=parseDNA('rs1\t1\t100\tAC\nrs1\t1\t100\tCA\nrs2\t1\t101\tTT');
  assert.equal(data.records.size,2);
  assert.equal(data.duplicates,1);
  assert.equal(data.conflicts,0);
});
test('conflicting duplicate calls are discarded; later duplicates cannot re-enable them',()=>{
  const data=parseDNA('rs1\t1\t100\tAA\nrs1\t1\t100\tGG\nrs1\t1\t100\tAA\nrs2\t2\t200\tCT');
  assert.equal(data.records.has('rs1'),false);
  assert.equal(data.records.get('rs2').genotype,'CT');
  assert.equal(data.conflicts,1);
  assert.equal(data.duplicates,2);
});
test('conflicting coordinates for the same rsID also invalidate it',()=>{
  const data=parseDNA('rs1\t1\t100\tAA\nrs1\t1\t200\tAA\nrs2\t2\t200\tCT');
  assert.equal(data.records.has('rs1'),false);
});
test('reject malformed data, bad alleles, invalid chromosomes, positions',()=>{
  assert.throws(()=>parseDNA('not raw DNA'),/Unrecognized format/);
  assert.throws(()=>parseDNA('rsid,chromosome,position,genotype\nrs1,1,0,AA'),/No valid rsID/);
  assert.throws(()=>parseDNA('rsid,chromosome,position,genotype\nrs1,99,100,AA'),/No valid rsID/);
  assert.throws(()=>parseDNA('rsid,chromosome,position,genotype\nrs1,1,100,NN'),/No valid rsID/);
  assert.throws(()=>parseDNA('rsid\tchromosome\tposition\tannotation\nrs1\t1\t100\tAA'),/missing genotype/);
});
test('normalizers reject indels and do not infer clinical calls from no-calls',()=>{
  assert.equal(normalizeGenotype('ca'),'AC');
  assert.equal(normalizeGenotype('G A'),'AG');
  assert.equal(normalizeGenotype('AA'),'AA');
  assert.equal(normalizeGenotype('N/A'),null);
  assert.equal(normalizeGenotype('DEL'),null);
  assert.equal(normalizeChromosome('chr23'),null);
  assert.equal(normalizeChromosome('chrM'),'MT');
  assert.equal(isNoCall('--'),true);
  assert.equal(isNoCall('00'),true);
  assert.equal(isCalledDiploidSnp('II'),false);
  assert.equal(isCalledDiploidSnp('A'),false);
  assert.equal(isCalledDiploidSnp('AA'),true);
});
test('large genotype export parses all valid unique rsIDs without network access',()=>{
  const lines=['# build 37','# rsid\tchromosome\tposition\tgenotype'];
  for(let i=1;i<=12000;i++)lines.push('rs'+i+'\t1\t'+(i+1000)+'\tAG');
  const r=parseDNA(lines.join('\n'));
  assert.equal(r.records.size,12000);
  assert.equal(r.records.get('rs10000').genotype,'AG');
});
